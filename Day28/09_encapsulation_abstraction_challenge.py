# Common mistakes
# - Double underscore ko complete security protection samajhna.
# - Encapsulation ko sirf private variables tak limited samajhna.
# - Abstract method ko child class mein implement karna bhool jaana.
# - ABC aur @abstractmethod ko import karna bhool jaana.
# - Abstraction aur encapsulation ko same concept samajhna.
# - Validation ke bina important data modify karne dena.


# Interview questions
# Q1. What is encapsulation in Python?
# Encapsulation combines data and related methods in a class and provides controlled access to that data.

# Q2. What is abstraction?
# Abstraction hides unnecessary implementation details and exposes essential functionality through a simple interface.

# Q3. Does Python support private variables?
# Python uses double-underscore name mangling for attributes such as __balance, but this is not strict privacy or security.

# Q4. What is an abstract class?
# An abstract class defines a common interface and can require child classes to implement specific methods.

# Q5. What is @abstractmethod?
# It marks a method as abstract, requiring concrete subclasses to implement it before they can be instantiated.

# Q6. What is the difference between encapsulation and abstraction?
# Encapsulation focuses on organizing data and controlling access, while abstraction focuses on hiding implementation complexity.