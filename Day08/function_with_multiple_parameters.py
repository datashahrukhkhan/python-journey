
# Function with Multiple Parameters
def add(a, b):
    print(a + b)
    print(a - b)
    print(a * b)
    print(a / b)
    print(a % b)

add(20, 10)


# Another example of a function with multiple parameters
def student_info(name, age):
    print("Name:", name)
    print("Age:", age)

student_info("Shahrukh Khan", 22)
student_info("Aayat Bano", 20)















