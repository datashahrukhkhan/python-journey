# Function with Parameters
# A function can receive information.

# Parameter → variable inside function definition
# Argument → actual value passed to function

# here name is a parameter. A parameter is a variable that is used to pass information into a function.
# And shahrukh is an argument. An argument is the actual value that is passed into a function when it is called.

def greet(name):
    print("Hello", name)

greet("Shahrukh")
greet("Rahul")
greet("Aman")