# Tuple Methods

# Tuples have a limited set of methods compared to lists. The two main methods available for tuples are:
# 1. count() - Returns the number of occurrences of a value in the tuple.
# 2. index() - Returns the index of the first occurrence of a value in the tuple.
# Tuples have fewer methods than lists because they cannot be modified.


# count() method
my_tuple = (10, 20, 10, 30, 10)
print(my_tuple.count(10))  # Output: 3


# index() method
my_tuple = (10, 20, 10, 30, 10)
print(my_tuple.index(10))  # Output: 0









