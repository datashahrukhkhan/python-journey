cubes = (x ** 3 for x in range(1, 6))

for cube in cubes:
    print(cube)


# This code demonstrates the use of a generator expression to create a sequence of cubes for numbers from 1 to 5.
# syntax: 
# (expression for item in iterable)
# that means we define a generator expression that produces values based on the specified expression for each item in the iterable (in this case, the range of numbers from 1 to 5).






