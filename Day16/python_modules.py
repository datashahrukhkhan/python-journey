# Module kya hota h?
# A module is a file containing Python definitions and statements. The file name is the module name with the suffix .py appended. Modules can define functions, classes, and variables, and can also include runnable code.
# Module = ek Python file (.py) jisme reusable code hota hai.

# Agar tumhara code bada ho raha hai, to sab kuch ek hi file mein likhne ke bajay code ko multiple .py files mein divide kar sakte ho.

# Module = Code ka separate box


# Modules ki zarurat kyu hai?
# Agar tum ek hi file mein 1000+ lines likhoge, code difficult ho jayega.

