# remove()
# Removes a specific value

fruits = ["apple", "banana", "mango"]

print(fruits)

fruits.remove("banana")

print(fruits)

# ---------------

# pop()
# Removes an element using its index

fruits = ["a", "b", "m"]

print(fruits)

fruits.pop(1)

print(fruits)


