# | Method      | Purpose           |
# | ----------- | ----------------- |
# | `append()`  | Add at end        |
# | `insert()`  | Add at position   |
# | `remove()`  | Remove value      |
# | `pop()`     | Remove by index   |
# | `sort()`    | Sort list         |
# | `reverse()` | Reverse list      |
# | `index()`   | Find position     |
# | `count()`   | Count occurrences |
# | `clear()`   | Remove everything |
