# What is an Argument?
# Function ko jo actual value dete ho, usse argument kehte hain.

def greet(name):
    print("Hello", name)

greet("Shahrukh")


# name       → Parameter
# "Shahrukh" → Argument

# Easy memory:-
# Parameter = function ke andar variable
# Argument = function ko di gayi actual value


