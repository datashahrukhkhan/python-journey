# Positional vs Keyword
def introduce(name, age, city):
    print(name, age, city)

# Positional arguments
introduce("Aayat", 18, "jaipur")

# Keyword arguments
# introduce(age=20, name="Shahrukh", city="Delhi")

introduce(
    age=20, 
    name="Shahrukh", 
    city="Delhi"
)


# Difference
# Positional → Position matters
# Keyword    → Parameter name matters









