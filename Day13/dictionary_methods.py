# Dictionary Methods 🔥

student = {
    'name': 'Sapna', 
    'age': 19, 
    'course': 'BBA'
}

# keys()   → Keys
# values() → Values
# items()  → Key + Value


# keys()
print(student.keys()) #Gets all keys

# values()
print(student.values()) #Gets all values

# items()
print(student.items()) #Gets all Key + Value














