# Comprehension kya hoti hai?

# Comprehension ek short aur clean way hai collection create karne ka.

# Normal way:-
numbers = []

for i in range(1, 6):
    numbers.append(i)

print(numbers)


# Comprehension:-
numbers = [i for i in range(1, 6)]

print(numbers)


